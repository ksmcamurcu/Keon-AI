package com.example.util

import android.app.DownloadManager
import android.content.BroadcastReceiver
import android.content.Context
import android.content.Intent
import android.content.IntentFilter
import android.database.Cursor
import android.net.Uri
import android.os.Build
import android.os.Environment
import android.widget.Toast
import androidx.core.content.FileProvider
import kotlinx.coroutines.channels.awaitClose
import kotlinx.coroutines.delay
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.callbackFlow
import kotlinx.coroutines.flow.flow
import java.io.File

/**
 * Status representation for DownloadManager operations.
 */
enum class DownloadStatus {
    PENDING,
    RUNNING,
    PAUSED,
    SUCCESSFUL,
    FAILED,
    UNKNOWN
}

/**
 * Reactive progress and state event emitted during download operations.
 */
sealed class DownloadEvent {
    object Idle : DownloadEvent()
    
    data class Progress(
        val downloadId: Long,
        val bytesDownloaded: Long,
        val totalBytes: Long,
        val progressPercentage: Float,
        val status: DownloadStatus
    ) : DownloadEvent()

    data class Success(
        val downloadId: Long,
        val localUri: Uri,
        val filePath: String?,
        val totalBytes: Long
    ) : DownloadEvent()

    data class Paused(
        val downloadId: Long,
        val reasonCode: Int,
        val reasonMessage: String
    ) : DownloadEvent()

    data class Failed(
        val downloadId: Long,
        val reasonCode: Int,
        val errorMessage: String
    ) : DownloadEvent()
}

/**
 * Contract for handling file downloads directly on Android devices without external redirects.
 */
interface Downloader {
    /**
     * Enqueues a new download using the system DownloadManager.
     * @return downloadId generated by Android DownloadManager, or -1L on failure
     */
    fun enqueueDownload(
        url: String,
        fileName: String,
        title: String = fileName,
        description: String = "Dosya indiriliyor...",
        mimeType: String? = null,
        destinationDirectory: String = Environment.DIRECTORY_DOWNLOADS,
        showNotification: Boolean = true,
        headers: Map<String, String> = emptyMap()
    ): Long

    /**
     * Observes real-time progress for a given downloadId.
     */
    fun observeDownloadProgress(downloadId: Long, pollIntervalMs: Long = 250L): Flow<DownloadEvent>

    /**
     * Observes completion of a download via system BroadcastReceiver.
     */
    fun observeDownloadCompletion(downloadId: Long): Flow<Uri?>

    /**
     * Queries current status synchronously for a given downloadId.
     */
    fun queryStatus(downloadId: Long): DownloadEvent

    /**
     * Cancels / removes a download task and cleans up partial files.
     */
    fun cancelDownload(downloadId: Long): Boolean

    /**
     * Retrieves the file URI for a completed download.
     */
    fun getDownloadedFileUri(downloadId: Long): Uri?

    /**
     * Retrieves the local File instance for a completed download, if available.
     */
    fun getDownloadedFile(downloadId: Long): File?

    /**
     * Directly launches the installation intent for an APK without browser redirects.
     */
    fun installApk(file: File): Boolean

    /**
     * Directly launches installation for a completed download by its downloadId.
     */
    fun installDownloadedApk(downloadId: Long): Boolean
}

/**
 * Robust implementation of [Downloader] leveraging Android's native [DownloadManager] API.
 * Handles storage destination fallback, FileProvider URI conversion, progress polling, and direct installation.
 */
class AndroidDownloader(
    private val context: Context
) : Downloader {

    private val downloadManager: DownloadManager? by lazy {
        context.getSystemService(Context.DOWNLOAD_SERVICE) as? DownloadManager
    }

    override fun enqueueDownload(
        url: String,
        fileName: String,
        title: String,
        description: String,
        mimeType: String?,
        destinationDirectory: String,
        showNotification: Boolean,
        headers: Map<String, String>
    ): Long {
        val manager = downloadManager ?: return -1L

        return try {
            val uri = Uri.parse(url)
            val request = DownloadManager.Request(uri).apply {
                setTitle(title)
                setDescription(description)
                setAllowedOverMetered(true)
                setAllowedOverRoaming(true)
                setAllowedNetworkTypes(
                    DownloadManager.Request.NETWORK_WIFI or DownloadManager.Request.NETWORK_MOBILE
                )

                if (showNotification) {
                    setNotificationVisibility(
                        DownloadManager.Request.VISIBILITY_VISIBLE_NOTIFY_COMPLETED
                    )
                } else {
                    setNotificationVisibility(
                        DownloadManager.Request.VISIBILITY_HIDDEN
                    )
                }

                mimeType?.let { setMimeType(it) }

                headers.forEach { (key, value) ->
                    addRequestHeader(key, value)
                }

                // Destination in Public External Downloads or app-specific fallback
                try {
                    setDestinationInExternalPublicDir(destinationDirectory, fileName)
                } catch (e: Exception) {
                    val fallbackFile = File(context.getExternalFilesDir(destinationDirectory), fileName)
                    setDestinationUri(Uri.fromFile(fallbackFile))
                }
            }

            manager.enqueue(request)
        } catch (e: Exception) {
            e.printStackTrace()
            -1L
        }
    }

    override fun observeDownloadProgress(downloadId: Long, pollIntervalMs: Long): Flow<DownloadEvent> = flow {
        if (downloadId <= 0) {
            emit(DownloadEvent.Failed(downloadId, -1, "Geçersiz indirme kimliği"))
            return@flow
        }

        var isTerminal = false
        while (!isTerminal) {
            val currentStatus = queryStatus(downloadId)
            emit(currentStatus)

            when (currentStatus) {
                is DownloadEvent.Success,
                is DownloadEvent.Failed -> {
                    isTerminal = true
                }
                else -> {
                    delay(pollIntervalMs)
                }
            }
        }
    }

    override fun observeDownloadCompletion(downloadId: Long): Flow<Uri?> = callbackFlow {
        val receiver = object : BroadcastReceiver() {
            override fun onReceive(c: Context?, intent: Intent?) {
                if (intent?.action == DownloadManager.ACTION_DOWNLOAD_COMPLETE) {
                    val id = intent.getLongExtra(DownloadManager.EXTRA_DOWNLOAD_ID, -1L)
                    if (id == downloadId) {
                        val fileUri = getDownloadedFileUri(downloadId)
                        trySend(fileUri)
                        close()
                    }
                }
            }
        }

        val intentFilter = IntentFilter(DownloadManager.ACTION_DOWNLOAD_COMPLETE)
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU) {
            context.registerReceiver(receiver, intentFilter, Context.RECEIVER_EXPORTED)
        } else {
            context.registerReceiver(receiver, intentFilter)
        }

        awaitClose {
            try {
                context.unregisterReceiver(receiver)
            } catch (e: Exception) {
                // Receiver may already be unregistered
            }
        }
    }

    override fun queryStatus(downloadId: Long): DownloadEvent {
        val manager = downloadManager ?: return DownloadEvent.Failed(
            downloadId, -1, "DownloadManager servisi başlatılamadı"
        )

        val query = DownloadManager.Query().setFilterById(downloadId)
        var cursor: Cursor? = null
        return try {
            cursor = manager.query(query)
            if (cursor != null && cursor.moveToFirst()) {
                val statusIndex = cursor.getColumnIndex(DownloadManager.COLUMN_STATUS)
                val reasonIndex = cursor.getColumnIndex(DownloadManager.COLUMN_REASON)
                val downloadedBytesIndex = cursor.getColumnIndex(DownloadManager.COLUMN_BYTES_DOWNLOADED_SO_FAR)
                val totalBytesIndex = cursor.getColumnIndex(DownloadManager.COLUMN_TOTAL_SIZE_BYTES)
                val localUriIndex = cursor.getColumnIndex(DownloadManager.COLUMN_LOCAL_URI)

                val status = if (statusIndex != -1) cursor.getInt(statusIndex) else -1
                val reason = if (reasonIndex != -1) cursor.getInt(reasonIndex) else 0
                val downloadedBytes = if (downloadedBytesIndex != -1) cursor.getLong(downloadedBytesIndex) else 0L
                val totalBytes = if (totalBytesIndex != -1) cursor.getLong(totalBytesIndex) else 0L
                val localUriString = if (localUriIndex != -1) cursor.getString(localUriIndex) else null

                val progress = if (totalBytes > 0) {
                    (downloadedBytes.toFloat() / totalBytes.toFloat()).coerceIn(0f, 1f)
                } else 0f

                when (status) {
                    DownloadManager.STATUS_PENDING -> {
                        DownloadEvent.Progress(
                            downloadId = downloadId,
                            bytesDownloaded = downloadedBytes,
                            totalBytes = totalBytes,
                            progressPercentage = progress,
                            status = DownloadStatus.PENDING
                        )
                    }
                    DownloadManager.STATUS_RUNNING -> {
                        DownloadEvent.Progress(
                            downloadId = downloadId,
                            bytesDownloaded = downloadedBytes,
                            totalBytes = totalBytes,
                            progressPercentage = progress,
                            status = DownloadStatus.RUNNING
                        )
                    }
                    DownloadManager.STATUS_PAUSED -> {
                        DownloadEvent.Paused(
                            downloadId = downloadId,
                            reasonCode = reason,
                            reasonMessage = getPausedReasonMessage(reason)
                        )
                    }
                    DownloadManager.STATUS_SUCCESSFUL -> {
                        val uri = localUriString?.let { Uri.parse(it) } ?: getDownloadedFileUri(downloadId) ?: Uri.EMPTY
                        val file = getDownloadedFile(downloadId)
                        DownloadEvent.Success(
                            downloadId = downloadId,
                            localUri = uri,
                            filePath = file?.absolutePath,
                            totalBytes = if (totalBytes > 0) totalBytes else (file?.length() ?: downloadedBytes)
                        )
                    }
                    DownloadManager.STATUS_FAILED -> {
                        DownloadEvent.Failed(
                            downloadId = downloadId,
                            reasonCode = reason,
                            errorMessage = getFailedReasonMessage(reason)
                        )
                    }
                    else -> {
                        DownloadEvent.Progress(
                            downloadId = downloadId,
                            bytesDownloaded = downloadedBytes,
                            totalBytes = totalBytes,
                            progressPercentage = progress,
                            status = DownloadStatus.UNKNOWN
                        )
                    }
                }
            } else {
                DownloadEvent.Failed(downloadId, -1, "İndirme görevi bulunamadı")
            }
        } catch (e: Exception) {
            DownloadEvent.Failed(downloadId, -1, e.localizedMessage ?: "Sorgulama hatası")
        } finally {
            cursor?.close()
        }
    }

    override fun cancelDownload(downloadId: Long): Boolean {
        val manager = downloadManager ?: return false
        return try {
            manager.remove(downloadId) > 0
        } catch (e: Exception) {
            false
        }
    }

    override fun getDownloadedFileUri(downloadId: Long): Uri? {
        val manager = downloadManager ?: return null
        return try {
            manager.getUriForDownloadedFile(downloadId)
        } catch (e: Exception) {
            null
        }
    }

    override fun getDownloadedFile(downloadId: Long): File? {
        val manager = downloadManager ?: return null
        val query = DownloadManager.Query().setFilterById(downloadId)
        var cursor: Cursor? = null
        return try {
            cursor = manager.query(query)
            if (cursor != null && cursor.moveToFirst()) {
                val localUriIndex = cursor.getColumnIndex(DownloadManager.COLUMN_LOCAL_URI)
                if (localUriIndex != -1) {
                    val uriString = cursor.getString(localUriIndex)
                    if (uriString != null) {
                        val uri = Uri.parse(uriString)
                        if (uri.scheme == "file") {
                            File(uri.path ?: return null)
                        } else {
                            // Try resolving standard downloads path
                            null
                        }
                    } else null
                } else null
            } else null
        } catch (e: Exception) {
            null
        } finally {
            cursor?.close()
        }
    }

    override fun installApk(file: File): Boolean {
        return try {
            if (!file.exists()) return false

            val apkUri: Uri = FileProvider.getUriForFile(
                context,
                "${context.packageName}.fileprovider",
                file
            )

            val installIntent = Intent(Intent.ACTION_VIEW).apply {
                setDataAndType(apkUri, "application/vnd.android.package-archive")
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            }
            context.startActivity(installIntent)
            true
        } catch (e: Exception) {
            e.printStackTrace()
            false
        }
    }

    override fun installDownloadedApk(downloadId: Long): Boolean {
        return try {
            // First attempt with resolved file
            val file = getDownloadedFile(downloadId)
            if (file != null && file.exists()) {
                return installApk(file)
            }

            // Secondary attempt with manager Uri
            val uri = getDownloadedFileUri(downloadId) ?: return false
            val installIntent = Intent(Intent.ACTION_VIEW).apply {
                setDataAndType(uri, "application/vnd.android.package-archive")
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            }
            context.startActivity(installIntent)
            true
        } catch (e: Exception) {
            e.printStackTrace()
            false
        }
    }

    private fun getPausedReasonMessage(reason: Int): String {
        return when (reason) {
            DownloadManager.PAUSED_WAITING_TO_RETRY -> "Yeniden deneniyor..."
            DownloadManager.PAUSED_WAITING_FOR_NETWORK -> "Ağ bağlantısı bekleniyor..."
            DownloadManager.PAUSED_QUEUED_FOR_WIFI -> "Wi-Fi bağlantısı bekleniyor..."
            DownloadManager.PAUSED_UNKNOWN -> "İndirme duraklatıldı"
            else -> "Duraklatıldı ($reason)"
        }
    }

    private fun getFailedReasonMessage(reason: Int): String {
        return when (reason) {
            DownloadManager.ERROR_CANNOT_RESUME -> "İndirme devam ettirilemedi"
            DownloadManager.ERROR_DEVICE_NOT_FOUND -> "Depolama aygıtı bulunamadı"
            DownloadManager.ERROR_FILE_ALREADY_EXISTS -> "Dosya zaten mevcut"
            DownloadManager.ERROR_FILE_ERROR -> "Depolama/Dosya hatası"
            DownloadManager.ERROR_HTTP_DATA_ERROR -> "Ağ veri aktarım hatası"
            DownloadManager.ERROR_INSUFFICIENT_SPACE -> "Yetersiz depolama alanı"
            DownloadManager.ERROR_TOO_MANY_REDIRECTS -> "Çok fazla yönlendirme"
            DownloadManager.ERROR_UNHANDLED_HTTP_CODE -> "Sunucu yanıt vermedi"
            DownloadManager.ERROR_UNKNOWN -> "Bilinmeyen bir hata oluştu"
            else -> "İndirme başarısız oldu ($reason)"
        }
    }
}
